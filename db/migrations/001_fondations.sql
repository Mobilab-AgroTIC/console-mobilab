-- 1. Rôles techniques (§2.3, §3.7). Les mots de passe ne sont jamais écrits ici :
--    migrate les pose depuis l'environnement (PG_*_PASSWORD) s'ils sont fournis.
DO $do$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'mobilab_owner') THEN
        CREATE ROLE mobilab_owner NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'svc_nodered') THEN
        CREATE ROLE svc_nodered NOLOGIN BYPASSRLS;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'svc_console') THEN
        CREATE ROLE svc_console NOLOGIN BYPASSRLS CREATEROLE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'clients') THEN
        CREATE ROLE clients NOLOGIN;
    END IF;
END
$do$;
GRANT clients TO svc_console WITH ADMIN TRUE, INHERIT FALSE, SET FALSE;

-- 2. Schéma app : configuration et état, lu et écrit par les seuls comptes de service.
CREATE SCHEMA IF NOT EXISTS app AUTHORIZATION mobilab_owner;
REVOKE ALL ON SCHEMA app FROM PUBLIC;
CREATE SEQUENCE IF NOT EXISTS app.tenant_slug_seq;

CREATE TABLE IF NOT EXISTS app.schema_migrations (
    version    text PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app.people (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telegram_user_id         bigint UNIQUE,
    display_name             text NOT NULL,
    source                   text NOT NULL DEFAULT 'bot' CHECK (source IN ('bot', 'admin', 'grafana')),
    is_admin                 boolean NOT NULL DEFAULT false,
    grafana_login            text UNIQUE,
    grafana_user_id          integer,
    grafana_password_sent_at timestamptz,
    profile                  jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(profile) = 'object'),
    settings                 jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(settings) = 'object'),
    access_requested_at      timestamptz,
    unreachable_since        timestamptz,
    created_at               timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app.tenants (
    slug                         text PRIMARY KEY CHECK (slug ~ '^f[0-9]{4,}$'),
    display_name                 text NOT NULL,
    ttn_app_id                   text UNIQUE,
    grafana_org_id               integer UNIQUE,
    pg_role                      text UNIQUE,
    alert_chat_id                bigint CHECK (alert_chat_id < 0),
    alert_chat_unreachable_since timestamptz,
    status                       text NOT NULL DEFAULT 'en_creation' CHECK (status IN
                                   ('en_creation', 'en_attente_activation', 'actif', 'suspendu', 'suppression', 'supprime')),
    activated_at                 timestamptz,
    purge_after                  timestamptz,
    config                       jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(config) = 'object'),
    migration                    jsonb CHECK (migration IS NULL OR jsonb_typeof(migration) = 'object'),
    created_by                   bigint REFERENCES app.people(id),
    created_at                   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS app.memberships (
    person_id       bigint NOT NULL REFERENCES app.people(id) ON DELETE CASCADE,
    tenant_slug     text   NOT NULL REFERENCES app.tenants(slug),
    role            text   NOT NULL CHECK (role IN ('proprietaire', 'membre', 'conseiller')),
    grafana_role    text   CHECK (grafana_role IN ('Admin', 'Editor', 'Viewer')),
    receives_alerts boolean NOT NULL,
    status          text   NOT NULL DEFAULT 'actif' CHECK (status IN ('actif', 'en_attente_accord')),
    source          text   NOT NULL DEFAULT 'bot' CHECK (source IN ('bot', 'grafana')),
    granted_by      bigint REFERENCES app.people(id),
    granted_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (person_id, tenant_slug)
);

CREATE TABLE IF NOT EXISTS app.invitations (
    token       text PRIMARY KEY,
    kind        text NOT NULL CHECK (kind IN ('activation', 'new_client', 'join', 'groupe', 'admin')),
    tenant_slug text REFERENCES app.tenants(slug),
    payload     jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(payload) = 'object'),
    created_by  bigint REFERENCES app.people(id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    expires_at  timestamptz NOT NULL,
    used_by     bigint REFERENCES app.people(id),
    used_at     timestamptz,
    revoked_at  timestamptz
);

CREATE TABLE IF NOT EXISTS app.devices (
    dev_eui       text PRIMARY KEY CHECK (dev_eui ~ '^[0-9a-f]{16}$'),
    tenant_slug   text NOT NULL REFERENCES app.tenants(slug),
    name          text NOT NULL,
    join_eui      text CHECK (join_eui ~ '^[0-9a-f]{16}$'),
    model_key     text,
    probes        jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(probes) = 'object'),
    mode_override text,
    config        jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(config) = 'object'),
    ttn_status    text NOT NULL DEFAULT 'en_creation' CHECK (ttn_status IN
                    ('en_creation', 'enregistre', 'connecte', 'echec', 'supprime', 'v1', 'bascule')),
    created_by    bigint REFERENCES app.people(id),
    created_at    timestamptz NOT NULL DEFAULT now(),
    last_seen     timestamptz,
    last_rssi     real,
    last_snr      real,
    battery_mv    integer,
    last_values   jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(last_values) = 'object')
);
CREATE UNIQUE INDEX IF NOT EXISTS devices_nom ON app.devices (tenant_slug, lower(name)) WHERE ttn_status <> 'supprime';

CREATE TABLE IF NOT EXISTS app.alert_rules (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dev_eui     text NOT NULL REFERENCES app.devices(dev_eui) ON DELETE CASCADE,
    kind        text NOT NULL CHECK (kind IN ('threshold', 'state', 'silence', 'battery')),
    metric      text,
    min         double precision,
    max         double precision,
    for_minutes integer NOT NULL DEFAULT 0,
    params      jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(params) = 'object'),
    enabled     boolean NOT NULL DEFAULT true,
    created_by  bigint REFERENCES app.people(id),
    created_at  timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT seuil_une_borne CHECK (kind <> 'threshold' OR num_nonnulls(min, max) = 1)
);
CREATE UNIQUE INDEX IF NOT EXISTS alert_rules_seuil
    ON app.alert_rules (dev_eui, metric, (min IS NULL)) WHERE kind = 'threshold';
CREATE UNIQUE INDEX IF NOT EXISTS alert_rules_integrees
    ON app.alert_rules (dev_eui, kind, coalesce(metric, '')) WHERE kind <> 'threshold';

CREATE TABLE IF NOT EXISTS app.alert_state (
    rule_id          bigint PRIMARY KEY REFERENCES app.alert_rules(id) ON DELETE CASCADE,
    state            text NOT NULL DEFAULT 'ok' CHECK (state IN ('ok', 'alarm')),
    since            timestamptz NOT NULL DEFAULT now(),
    pending_since    timestamptz,
    last_value       double precision,
    last_notified_at timestamptz,
    reminded_at      timestamptz,
    muted_until      timestamptz,
    muted_by         bigint REFERENCES app.people(id)
);

CREATE TABLE IF NOT EXISTS app.commands (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dev_eui        text NOT NULL REFERENCES app.devices(dev_eui),
    action         text NOT NULL,
    f_port         smallint NOT NULL,
    payload_hex    text NOT NULL,
    correlation_id text UNIQUE,
    requested_by   bigint REFERENCES app.people(id),
    via            text NOT NULL DEFAULT 'bot' CHECK (via IN ('bot', 'admin', 'support')),
    status         text NOT NULL DEFAULT 'demandee' CHECK (status IN ('demandee', 'envoyee', 'confirmee', 'echec', 'annulee')),
    expires_at     timestamptz NOT NULL,
    chat_id        bigint,
    message_id     bigint,
    error          text,
    requested_at   timestamptz NOT NULL DEFAULT now(),
    sent_at        timestamptz,
    confirmed_at   timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS commands_une_en_cours ON app.commands (dev_eui) WHERE status IN ('demandee', 'envoyee');

CREATE TABLE IF NOT EXISTS app.jobs (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         text NOT NULL CHECK (kind IN (
                   'creer_client', 'grafana_personne', 'retirer_acces', 'ajouter_capteur', 'mise_en_service',
                   'verifier_join', 'corriger_codes', 'renommer_capteur', 'supprimer_capteur', 'deplacer_capteur',
                   'commande', 'commande_expiree', 'suspendre_client', 'reactiver_client', 'supprimer_client',
                   'purger_client', 'verifier_ferme', 'regenerer_tableaux', 'mdp_grafana',
                   'reprise_v1', 'import_historique', 'bascule_capteur', 'retour_v1')),
    tenant_slug  text,
    dev_eui      text,
    status       text NOT NULL DEFAULT 'en_attente' CHECK (status IN ('en_attente', 'en_cours', 'ok', 'echec', 'annule')),
    step         text,
    params       jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(params) = 'object'),
    result       jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(result) = 'object'),
    secret       bytea,
    attempts     integer NOT NULL DEFAULT 0,
    run_after    timestamptz NOT NULL DEFAULT now(),
    error        text,
    requested_by bigint REFERENCES app.people(id),
    chat_id      bigint,
    message_id   bigint,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS jobs_a_faire ON app.jobs (run_after) WHERE status = 'en_attente';

CREATE TABLE IF NOT EXISTS app.notifications (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at    timestamptz NOT NULL DEFAULT now(),
    audience      text NOT NULL CHECK (audience IN ('client', 'admin')),
    expediteur    text NOT NULL CHECK (expediteur IN ('nodered', 'service')),
    kind          text NOT NULL,
    tenant_slug   text,
    dev_eui       text,
    rule_ids      bigint[],
    transition    text CHECK (transition IN ('alarme', 'retour', 'rappel', 'info', 'admin')),
    valeur        double precision,
    details       jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(details) = 'object'),
    envoyer_apres timestamptz NOT NULL DEFAULT now(),
    statut        text NOT NULL DEFAULT 'a_envoyer' CHECK (statut IN
                    ('a_envoyer', 'en_cours', 'envoye', 'sans_destinataire', 'echec', 'ecarte')),
    destinataires jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(destinataires) = 'array'),
    erreur        text
);
CREATE INDEX IF NOT EXISTS notifications_a_envoyer ON app.notifications (envoyer_apres) WHERE statut = 'a_envoyer';

CREATE TABLE IF NOT EXISTS app.anomalies (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    raison         text NOT NULL CHECK (raison IN ('deveui_inconnu', 'mauvaise_application', 'capteur_supprime',
                     'modele_inconnu', 'decodage', 'deja_enregistre', 'webhook', 'derive', 'passerelle')),
    tenant_slug    text,
    dev_eui        text,
    application_id text,
    gateway_id     text,
    details        jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(details) = 'object'),
    trames         jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(trames) = 'array'),
    first_seen     timestamptz NOT NULL DEFAULT now(),
    last_seen      timestamptz NOT NULL DEFAULT now(),
    count          integer NOT NULL DEFAULT 1,
    notified_at    timestamptz,
    resolved_at    timestamptz,
    resolved_by    bigint REFERENCES app.people(id)
);
CREATE UNIQUE INDEX IF NOT EXISTS anomalies_ouvertes ON app.anomalies
    (raison, coalesce(tenant_slug, ''), coalesce(dev_eui, ''), coalesce(gateway_id, '')) WHERE resolved_at IS NULL;

CREATE TABLE IF NOT EXISTS app.gateways (
    gateway_id    text PRIMARY KEY,
    label         text,
    last_seen     timestamptz,
    missing_since timestamptz
);

CREATE TABLE IF NOT EXISTS app.audit (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at          timestamptz NOT NULL DEFAULT now(),
    actor_id    bigint REFERENCES app.people(id),
    via         text NOT NULL DEFAULT 'bot' CHECK (via IN ('bot', 'admin', 'support', 'systeme')),
    tenant_slug text,
    dev_eui     text,
    action      text NOT NULL,
    details     jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(details) = 'object')
);

CREATE TABLE IF NOT EXISTS app.bot_sessions (
    key        text PRIMARY KEY,
    value      jsonb NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- 3. Mesures au format long (§3.6) et trames brutes.
CREATE TABLE IF NOT EXISTS public.measures (
    time    timestamptz      NOT NULL,
    tenant  text             NOT NULL,
    dev_eui text             NOT NULL,
    metric  text             NOT NULL,
    value   double precision NOT NULL,
    UNIQUE (dev_eui, metric, time)
);
SELECT create_hypertable('public.measures', 'time', if_not_exists => TRUE);
CREATE INDEX IF NOT EXISTS measures_tenant_time_idx ON public.measures (tenant, time DESC);

-- public.uplinks existe déjà (V2 : une ligne par trame, clé name + time). La V3 y ajoute
-- les colonnes de la spec ; elle y écrit name = dev_eui.
CREATE TABLE IF NOT EXISTS public.uplinks (
    time           timestamptz NOT NULL,
    name           text        NOT NULL,
    tenant         text        NOT NULL,
    application_id text,
    f_port         smallint,
    f_cnt          bigint,
    frm_payload    bytea
);
SELECT create_hypertable('public.uplinks', 'time', if_not_exists => TRUE, migrate_data => TRUE);
ALTER TABLE public.uplinks ADD COLUMN IF NOT EXISTS dev_eui  text;
ALTER TABLE public.uplinks ADD COLUMN IF NOT EXISTS rssi     real;
ALTER TABLE public.uplinks ADD COLUMN IF NOT EXISTS snr      real;
ALTER TABLE public.uplinks ADD COLUMN IF NOT EXISTS gateways jsonb;
ALTER TABLE public.uplinks ADD COLUMN IF NOT EXISTS decoded  jsonb;
CREATE UNIQUE INDEX IF NOT EXISTS uplinks_name_time_uidx ON public.uplinks (name, time);
-- Clé V3 : une trame par capteur et par instant (ON CONFLICT (dev_eui, time) DO NOTHING).
-- Les lignes V2 ont dev_eui vide : NULL n'entre pas en conflit.
CREATE UNIQUE INDEX IF NOT EXISTS uplinks_dev_eui_time_uidx ON public.uplinks (dev_eui, time);
CREATE INDEX IF NOT EXISTS uplinks_tenant_time_idx ON public.uplinks (tenant, time DESC);

-- 4. Cloisonnement (§3.7) : chaque ferme ne lit que ses lignes.
ALTER TABLE public.measures ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.measures FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS measures_ferme ON public.measures;
CREATE POLICY measures_ferme ON public.measures FOR SELECT TO clients USING (tenant = current_user);

ALTER TABLE public.uplinks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.uplinks FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS uplinks_ferme ON public.uplinks;
CREATE POLICY uplinks_ferme ON public.uplinks FOR SELECT TO clients USING (tenant = current_user);

CREATE OR REPLACE VIEW public.capteurs WITH (security_barrier = true) AS
    SELECT dev_eui, name, model_key, ttn_status, last_seen, battery_mv, last_rssi, last_snr, last_values
    FROM app.devices
    WHERE tenant_slug = current_user;

-- 5. Propriétaires et droits.
DO $do$
DECLARE t record;
BEGIN
    FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'app' LOOP
        EXECUTE format('ALTER TABLE app.%I OWNER TO mobilab_owner', t.tablename);
    END LOOP;
END
$do$;
ALTER SEQUENCE app.tenant_slug_seq OWNER TO mobilab_owner;
ALTER TABLE public.measures OWNER TO mobilab_owner;
ALTER VIEW public.capteurs OWNER TO mobilab_owner;

GRANT USAGE ON SCHEMA app TO svc_nodered, svc_console;
GRANT USAGE ON SCHEMA public TO clients, svc_nodered, svc_console;
GRANT SELECT ON public.measures, public.uplinks, public.capteurs TO clients;

GRANT SELECT, INSERT, DELETE ON public.measures TO svc_nodered;
GRANT SELECT, INSERT ON public.uplinks TO svc_nodered;
GRANT UPDATE (decoded) ON public.uplinks TO svc_nodered;
GRANT SELECT ON app.tenants, app.people, app.memberships, app.devices, app.alert_rules, app.commands TO svc_nodered;
GRANT UPDATE (alert_chat_unreachable_since) ON app.tenants TO svc_nodered;
GRANT UPDATE (unreachable_since) ON app.people TO svc_nodered;
GRANT UPDATE (last_seen, last_rssi, last_snr, battery_mv, last_values, config, ttn_status) ON app.devices TO svc_nodered;
GRANT SELECT, INSERT, UPDATE ON app.alert_state TO svc_nodered;
GRANT UPDATE (status, sent_at, confirmed_at, error) ON app.commands TO svc_nodered;
GRANT SELECT, INSERT, DELETE ON app.notifications TO svc_nodered;
GRANT UPDATE (statut, destinataires, erreur) ON app.notifications TO svc_nodered;
GRANT SELECT, INSERT, UPDATE ON app.anomalies TO svc_nodered;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA app TO svc_nodered;

GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA app TO svc_console;
GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA app TO svc_console;
GRANT SELECT, INSERT, DELETE ON public.measures, public.uplinks TO svc_console;
ALTER DEFAULT PRIVILEGES FOR ROLE mobilab_owner IN SCHEMA app
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO svc_console;
ALTER DEFAULT PRIVILEGES FOR ROLE mobilab_owner IN SCHEMA app
    GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO svc_console;
-- Fermer les sessions Grafana d'une ferme suspendue (§6.9).
GRANT pg_signal_backend TO svc_console;

-- 6. Connexion à la base. Le REVOKE ... FROM PUBLIC de §3.7 attendra la fin de la V2 :
--    les rôles V2 (un par tenant) se connectent encore grâce au droit de PUBLIC.
DO $do$
BEGIN
    EXECUTE format('GRANT CONNECT ON DATABASE %I TO clients, svc_nodered, svc_console, mobilab_owner', current_database());
END
$do$;
