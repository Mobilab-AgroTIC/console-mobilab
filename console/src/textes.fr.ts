/** Remplace les {clés} d'un gabarit. Une clé absente reste visible, pour que les tests la repèrent. */
export function f(gabarit: string, valeurs: Record<string, string | number | null | undefined> = {}): string {
  return gabarit.replace(/\{(\w+)\}/g, (m, k: string) => {
    const v = valeurs[k];
    return v === undefined || v === null ? m : String(v);
  });
}
